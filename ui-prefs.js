export function initUiPrefs() {
  if (document.querySelector('.ui-prefs')) return;
  if (!document.getElementById('ui-prefs-styles')) {
    const st = document.createElement('style');
    st.id = 'ui-prefs-styles';
    st.textContent = STYLE;
    document.head.appendChild(st);
  }

  const group = document.createElement('div');
  group.className = 'ui-prefs';
  group.innerHTML = `
    <button type="button" class="ui-prefs-btn" id="ui-theme-btn"></button>
    <label class="ui-prefs-lang" title="Language / Wika">
      ${GLOBE}
      <select id="ui-lang-select" aria-label="Language / Wika">
        <option value="en">EN</option>
        <option value="fil">FIL</option>
      </select>
    </label>`;
  // Never translate the picker itself.
  group.setAttribute('data-no-translate', '');

  const themeBtn = group.querySelector('#ui-theme-btn');
  const paintThemeBtn = () => {
    const dark = currentTheme() === 'dark';
    themeBtn.innerHTML = dark ? SUN : MOON;
    const label = currentLang() === 'fil'
      ? (dark ? 'Gawing maliwanag' : 'Gawing madilim')
      : (dark ? 'Switch to light mode' : 'Switch to dark mode');
    themeBtn.setAttribute('aria-label', label);
    themeBtn.title = label;
  };
  themeBtn.addEventListener('click', () => { setTheme(currentTheme() === 'dark' ? 'light' : 'dark'); paintThemeBtn(); });
  paintThemeBtn();

  const langSel = group.querySelector('#ui-lang-select');
  langSel.value = currentLang();
  langSel.addEventListener('change', () => { setLanguage(langSel.value); paintThemeBtn(); });

  // Sit next to the date / (?) help button in the top bar.
  const dateEl = document.getElementById('current-date');
  const helpBtn = document.getElementById('page-help-btn');
  if (helpBtn) helpBtn.insertAdjacentElement('beforebegin', group);
  else if (dateEl && dateEl.parentElement) {
    if (dateEl.parentElement.tagName === 'HEADER') {
      const wrap = document.createElement('div');
      wrap.className = 'help-date-wrap';
      wrap.style.display = 'flex'; wrap.style.alignItems = 'center'; wrap.style.gap = '0.625rem';
      dateEl.parentElement.insertBefore(wrap, dateEl);
      wrap.append(group, dateEl);
    } else dateEl.insertAdjacentElement('beforebegin', group);
  } else {
    group.classList.add('ui-prefs-standalone');
    document.body.appendChild(group);
  }

  if (currentLang() === 'fil') {
    startTranslating()
      .catch(err => console.error('Could not load Filipino text:', err))
      .finally(() => document.documentElement.classList.remove('i18n-pending'));
  }
}
