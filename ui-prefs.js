/* ============================================
   SacraDigit — display preferences
   Light/Dark theme + English/Filipino, for every
   role (admin, parishioner, ITech, Media). Each
   role's shell script calls initUiPrefs(), which
   puts both controls in the top bar next to the
   date and the (?) help button.

   Saved per browser (localStorage):
     sacradigit_theme = 'light' | 'dark'
     sacradigit_lang  = 'en' | 'fil'
   A tiny inline script in each page's <head>
   applies the saved theme before the page is
   drawn (no white flash); see THEME_BOOT below.

   Dark colours:  theme-dark.css (generated by
                  tools/build-dark-theme.mjs)
   Filipino text: i18n-fil.js (English → Filipino
                  dictionary), applied by translatePage()
   ============================================ */

const THEME_KEY = 'sacradigit_theme';
const LANG_KEY = 'sacradigit_lang';

/** The inline <head> snippet every page carries (kept here for reference). */
export const THEME_BOOT = `try{var t=localStorage.getItem('${THEME_KEY}');if(t==='dark')document.documentElement.dataset.theme='dark';if(localStorage.getItem('${LANG_KEY}')==='fil'){document.documentElement.lang='fil';document.documentElement.classList.add('i18n-pending');setTimeout(function(){document.documentElement.classList.remove('i18n-pending')},1500)}}catch(e){}`;

const read = (k) => { try { return localStorage.getItem(k); } catch { return null; } };
const write = (k, v) => { try { localStorage.setItem(k, v); } catch { /* private mode */ } };

export const currentTheme = () => (document.documentElement.dataset.theme === 'dark' ? 'dark' : 'light');
export const currentLang = () => (read(LANG_KEY) === 'fil' ? 'fil' : 'en');

export function setTheme(theme) {
  if (theme === 'dark') document.documentElement.dataset.theme = 'dark';
  else delete document.documentElement.dataset.theme;
  write(THEME_KEY, theme);
  document.dispatchEvent(new CustomEvent('sacradigit:theme', { detail: theme }));
}

/* ------------------------------------------
   Translation (English → Filipino)
------------------------------------------ */

let dict = null;        // Map of normalized English → Filipino
let patterns = [];      // [RegExp, replacement] for text with numbers/names in it
let observer = null;
const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA', 'CODE', 'PRE', 'svg', 'SVG', 'title']);
const ATTRS = ['placeholder', 'title', 'aria-label'];

const norm = (s) => s.replace(/\s+/g, ' ').trim();

const MONTHS_FIL = { January: 'Enero', February: 'Pebrero', March: 'Marso', April: 'Abril', May: 'Mayo', June: 'Hunyo', July: 'Hulyo', August: 'Agosto', September: 'Setyembre', October: 'Oktubre', November: 'Nobyembre', December: 'Disyembre',
  Jan: 'Ene', Feb: 'Peb', Mar: 'Mar', Apr: 'Abr', Jun: 'Hun', Jul: 'Hul', Aug: 'Ago', Sep: 'Set', Sept: 'Set', Oct: 'Okt', Nov: 'Nob', Dec: 'Dis' };
const DAYS_FIL = { Monday: 'Lunes', Tuesday: 'Martes', Wednesday: 'Miyerkules', Thursday: 'Huwebes', Friday: 'Biyernes', Saturday: 'Sabado', Sunday: 'Linggo',
  Mon: 'Lun', Tue: 'Mar', Wed: 'Miy', Thu: 'Huw', Fri: 'Biy', Sat: 'Sab', Sun: 'Lin' };
const DATE_WORD = new RegExp(`\\b(${[...Object.keys(MONTHS_FIL), ...Object.keys(DAYS_FIL)].sort((a, b) => b.length - a.length).join('|')})\\b`, 'g');
// Only touch month/day names inside something that looks like a date ("Sep 26, 2026", "Saturday, September 26").
const LOOKS_LIKE_DATE = /\b(\d{1,2},?\s+\d{4}|\d{4}|\w+day,|[A-Z][a-z]{2},\s+[A-Z][a-z]{2,8}\s+\d{1,2}|[A-Z][a-z]{2,8}\s+\d{1,2})\b/;

const translateDates = (s) => (LOOKS_LIKE_DATE.test(s) ? s.replace(DATE_WORD, (w) => MONTHS_FIL[w] || DAYS_FIL[w] || w) : s);

function translateOne(key) {
  const hit = dict.get(key);
  if (hit) return hit;
  for (const [re, rep] of patterns) {
    if (re.test(key)) return translateDates(key.replace(re, rep));
  }
  const dated = translateDates(key);
  return dated !== key ? dated : null;
}

function translateText(text) {
  const key = norm(text);
  if (!key) return null;
  const whole = translateOne(key);
  if (whole) return whole;
  // "Pet Blessing · requested for Sat, Sep 12", "First Offering — Made a first…"
  const sep = key.includes(' · ') ? ' · ' : key.includes(' — ') ? ' — ' : null;
  if (!sep) return null;
  const joined = key.split(sep).map(part => translateOne(part) || part).join(sep);
  return joined !== key ? joined : null;
}

/** Translate a piece of text (used by i18n-fil.js patterns for the parts they capture). */
export const t = (s) => (dict && translateText(s)) || s;

function translateTextNode(node) {
  const raw = node.nodeValue;
  if (!raw || !/[A-Za-z]/.test(raw)) return;
  const fil = translateText(raw);
  if (!fil || fil === norm(raw)) return;
  const lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
  node.nodeValue = lead + fil + trail;
}

function translateAttrs(el) {
  for (const a of ATTRS) {
    const v = el.getAttribute && el.getAttribute(a);
    if (!v) continue;
    const fil = translateText(v);
    if (fil && fil !== v) el.setAttribute(a, fil);
  }
  // <input type="button" value="…">
  if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit') && el.value) {
    const fil = translateText(el.value);
    if (fil) el.value = fil;
  }
}

// <textarea> content is never translated (people type there), but its placeholder is.
function attrsSkipped(el) {
  return !el || (el.closest && el.closest('[data-no-translate]'));
}

function skipped(el) {
  return !el || SKIP_TAGS.has(el.tagName) || (el.closest && el.closest('[data-no-translate], [contenteditable="true"]'));
}

function translateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    if (!skipped(root.parentElement)) translateTextNode(root);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  if (!attrsSkipped(root)) translateAttrs(root);
  if (skipped(root)) return;
  root.querySelectorAll('[placeholder], [title], [aria-label], input[type="button"], input[type="submit"]').forEach(el => { if (!attrsSkipped(el)) translateAttrs(el); });
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (skipped(n.parentElement) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) translateTextNode(n);
}

async function startTranslating() {
  if (!dict) {
    const mod = await import('./i18n-fil.js');
    dict = new Map(Object.entries(mod.FIL).map(([en, fil]) => [norm(en), fil]));
    patterns = mod.FIL_PATTERNS || [];
  }
  document.documentElement.lang = 'fil';
  const t = translateText(document.title);
  if (t) document.title = t;
  translateTree(document.body);
  // Keep translating whatever the page adds or changes later (tables, toasts, modals…).
  observer = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') translateTextNode(m.target);
      else if (m.type === 'attributes') translateAttrs(m.target);
      else m.addedNodes.forEach(translateTree);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}

export async function setLanguage(lang) {
  write(LANG_KEY, lang);
  if (lang === 'fil') {
    await startTranslating();
  } else {
    // Back to English: the original text is simply the page as served.
    window.location.reload();
  }
}

